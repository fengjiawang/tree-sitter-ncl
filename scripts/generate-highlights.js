#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const vocabulary = require('../data/ncl-vocabulary.json');
let query = fs.readFileSync(path.join(root, 'queries/highlights-base.scm'), 'utf8');
query = '; Generated by scripts/generate-highlights.js; edit highlights-base.scm instead.\n' + query;
for (const [key, capture] of [['functions', 'function.builtin'], ['customFunctions', 'function.custom']]) {
  // Chunk large sets for readable queries. The predicate operates on a whole
  // identifier node, so words in comments and strings cannot match.
  for (let i = 0; i < vocabulary[key].length; i += 80) {
    query += '\n((application_expression function: (identifier) @' + capture + ')\n';
    query += '  (#any-of? @' + capture + '\n    ';
    query += vocabulary[key].slice(i, i + 80).map(JSON.stringify).join('\n    ');
    query += '))\n';
  }
}
fs.writeFileSync(path.join(root, 'queries/highlights.scm'), query);
